def holiday_name(d: date) -> str | None:
    return FIXED_HOLIDAYS.get(d.strftime("%m-%d"))


def is_business_day(d: date) -> bool:
    return d.isoweekday() < 6 and holiday_name(d) is None


def next_business_day(d: date) -> date:
    """system.fn_next_business_day-тэй ижил: хамгийн ихдээ 15 өдөр урагшилна."""
    cur = d
    for _ in range(15):
        if is_business_day(cur):
            return cur
        cur += timedelta(days=1)
    return cur


def ts(d: date, hour: int = 10, minute: int = 0, second: int = 0) -> datetime:
    return datetime(d.year, d.month, d.day, hour, minute, second, tzinfo=UB_TZ)


def ts_rand(rng: Rng, d: date, start_hour: int = 9, end_hour: int = 18) -> datetime:
    return ts(d, rng.randint(start_hour, end_hour - 1), rng.randint(0, 59), rng.randint(0, 59))


def years_between(born: date, at: date) -> int:
    return at.year - born.year - ((at.month, at.day) < (born.month, born.day))


