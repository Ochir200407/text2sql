def D(x) -> Decimal:
    """Мөнгөн дүнг 2 оронтой Decimal болгоно (PostgreSQL round()-тэй ижил HALF_UP)."""
    if isinstance(x, Decimal):
        return x.quantize(CENT, rounding=ROUND_HALF_UP)
    return Decimal(str(x)).quantize(CENT, rounding=ROUND_HALF_UP)


def D4(x) -> Decimal:
    return (x if isinstance(x, Decimal) else Decimal(str(x))).quantize(Decimal("0.0001"), rounding=ROUND_HALF_UP)


class Rng:
    """random.Random-ийн нимгэн бүрхүүл — домэйнд хэрэгтэй тархалтууд."""

    def __init__(self, seed: int):
        self.r = random.Random(seed)

    def child(self, label: str) -> Rng:
        h = hashlib.sha256(f"{self.r.random()}:{label}".encode()).hexdigest()
        return Rng(int(h[:16], 16))

    def random(self) -> float:
        return self.r.random()

    def chance(self, p: float) -> bool:
        return self.r.random() < p

    def randint(self, a: int, b: int) -> int:
        return self.r.randint(a, b)

    def uniform(self, a: float, b: float) -> float:
        return self.r.uniform(a, b)

    def choice(self, seq):
        return self.r.choice(seq)

    def sample(self, seq, k: int):
        return self.r.sample(seq, k)

    def shuffle(self, seq) -> None:
        self.r.shuffle(seq)

    def weighted(self, items: dict | list):
        """{утга: жин} эсвэл [(утга, жин)] — жинтэй сонголт."""
        pairs = list(items.items()) if isinstance(items, dict) else list(items)
        total = sum(w for _, w in pairs)
        x = self.r.random() * total
        acc = 0.0
        for value, weight in pairs:
            acc += weight
            if x < acc:
                return value
        return pairs[-1][0]

    def lognormal(self, median: float, sigma: float) -> float:
        return median * math.exp(self.r.gauss(0.0, sigma))

    def gauss(self, mu: float, sigma: float) -> float:
        return self.r.gauss(mu, sigma)

    def uuid(self) -> uuid.UUID:
        return uuid.UUID(int=self.r.getrandbits(128), version=4)

    def date_between(self, start: date, end: date) -> date:
        if end <= start:
            return start
        return start + timedelta(days=self.r.randint(0, (end - start).days))

    def round_to(self, value: float, step: int) -> int:
        return max(step, int(round(value / step)) * step)


