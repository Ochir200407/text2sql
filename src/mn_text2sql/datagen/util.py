def add_months(d: date, months: int) -> date:
    """PostgreSQL-ийн `date + interval 'N months'`-тэй ижил (сарын сүүлээр хавчина)."""
    y = d.year + (d.month - 1 + months) // 12
    m = (d.month - 1 + months) % 12 + 1
    last = calendar.monthrange(y, m)[1]
    return date(y, m, min(d.day, last))


def month_end(d: date) -> date:
    return date(d.year, d.month, calendar.monthrange(d.year, d.month)[1])


def month_start(d: date) -> date:
    return date(d.year, d.month, 1)


def month_ends_between(start: date, end: date) -> list[date]:
    """start-аас хойшхи (start-ийн сарын сүүлийг оруулаад) end хүртэлх сарын сүүлийн өдрүүд."""
    out = []
    cur = month_end(start)
    while cur <= end:
        out.append(cur)
        cur = month_end(add_months(month_start(cur), 1))
    return out


